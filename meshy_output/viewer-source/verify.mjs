import { writeFile, readFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root=dirname(fileURLToPath(import.meta.url));
const out=resolve(root,'..');
const browser=await chromium.launch({channel:'chrome',headless:true});
const results={};
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request',r=>{if(/^https?:/.test(r.url())) requests.push(r.url());});
  await page.goto(pathToFileURL(resolve(root,'../../index.html')).href);
  await page.waitForFunction(()=>window.aurora3D?.renderer.info.render.calls>0,{},{timeout:30000});
  await page.screenshot({path:resolve(out,'aurora-logo-3d-preview.png')});
  results.initial=await page.evaluate(()=>({camera:window.aurora3D.camera.position.toArray(),triangles:window.aurora3D.triangles,originalDimensions:window.aurora3D.originalSize,drawCalls:window.aurora3D.renderer.info.render.calls,modelName:window.aurora3D.model.name,errorVisible:!document.querySelector('#status').hidden}));
  await page.mouse.move(740,430);await page.mouse.down();await page.mouse.move(1030,450,{steps:18});await page.mouse.up();
  await page.waitForTimeout(500);
  results.afterDrag=await page.evaluate(()=>window.aurora3D.camera.position.toArray());
  await page.screenshot({path:resolve(out,'aurora-logo-3d-side-view.png')});
  const beforeZoom=await page.evaluate(()=>window.aurora3D.camera.position.length());
  await page.mouse.wheel(0,-250);await page.waitForTimeout(400);
  results.zoomed=await page.evaluate((before)=>window.aurora3D.camera.position.length()<before,beforeZoom);
  await page.getByRole('button',{name:'Auto rotate',exact:true}).click();
  results.autoRotate=await page.evaluate(()=>window.aurora3D.controls.autoRotate);
  await page.getByRole('button',{name:'Reset view',exact:true}).click();
  results.reset=await page.evaluate(()=>({camera:window.aurora3D.camera.position.toArray(),spin:window.aurora3D.controls.autoRotate}));
  await page.getByRole('button',{name:'Wireframe',exact:true}).click();
  results.wireframe=await page.evaluate(()=>{const m=[];window.aurora3D.model.traverse(o=>{if(o.isMesh)(Array.isArray(o.material)?o.material:[o.material]).forEach(v=>m.push(v.wireframe));});return m.every(Boolean);});
  await page.getByRole('button',{name:'Wireframe',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Save PNG',exact:true}).click();
  const download=await downloadPromise;
  await download.saveAs(resolve(out,'aurora-logo-transparent-preview.png'));
  results.download={name:download.suggestedFilename(),bytes:(await readFile(resolve(out,'aurora-logo-transparent-preview.png'))).length};
  await page.locator('canvas').focus();
  await page.keyboard.press('ArrowLeft');
  results.keyboardRotated=await page.evaluate(initial=>window.aurora3D.camera.position.toArray().some((v,i)=>Math.abs(v-initial[i])>0.01),results.reset.camera);
  await page.keyboard.press('Home');
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
  await page.screenshot({path:resolve(out,'aurora-logo-3d-mobile.png')});
  results.mobile=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,canvas:document.querySelector('canvas').getBoundingClientRect().toJSON(),buttons:[...document.querySelectorAll('button')].map(b=>({label:b.textContent,box:b.getBoundingClientRect().toJSON()}))}));
  await page.setViewportSize({width:1280,height:720});await page.waitForTimeout(300);
  await page.screenshot({path:resolve(out,'aurora-logo-3d-small-desktop.png')});
  results.errors=errors;results.externalRequests=requests;
  const html=await readFile(resolve(root,'../../index.html'),'utf8');
  results.packaging={embeddedScripts:(html.match(/<script\b/g)||[]).length,externalScripts:/<script[^>]+src\s*=/.test(html),htmlBytes:Buffer.byteLength(html)};
  results.passed=!errors.length&&!requests.length&&results.zoomed&&results.autoRotate&&results.wireframe&&results.keyboardRotated&&!results.initial.errorVisible&&!results.mobile.overflow&&!results.reset.spin&&results.download.bytes>1000&&results.initial.originalDimensions[2]>0.1&&results.afterDrag.some((v,i)=>Math.abs(v-results.initial.camera[i])>0.1);
  await writeFile(resolve(out,'verification.json'),JSON.stringify(results,null,2));
  console.log(JSON.stringify(results,null,2));
  if(!results.passed) process.exitCode=1;
} finally { await browser.close(); }
